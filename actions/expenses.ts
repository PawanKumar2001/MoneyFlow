"use server";

import { db } from "@/lib/db";
import { auth } from "@/lib/auth";
import {
  getCache,
  setCache,
  deleteCache,
  deleteCachePattern,
  cacheKeys,
  TTL,
} from "@/lib/redis";

type ExpenseData = {
  name: string;
  category: string;
  amount: number;
  date: string;
};

export async function getExpenses(month: number, year: number) {
  const session = await auth();
  if (!session?.user?.id) return [];

  const userId = session.user.id;
  const cacheKey = cacheKeys.expenses(userId, month, year);

  // Try cache first
  const cached = await getCache<any[]>(cacheKey);
  if (cached) return cached;

  // Cache miss — fetch from DB
  const expenses = await db.expense.findMany({
    where: { userId, month, year },
    orderBy: { createdAt: "desc" },
  });

  // Store in cache
  await setCache(cacheKey, expenses, TTL.EXPENSES);

  return expenses;
}

export async function addExpense(data: ExpenseData) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  const userId = session.user.id;
  const date = new Date(data.date);
  const month = date.getMonth() + 1;
  const year = date.getFullYear();

  await db.expense.create({
    data: {
      userId,
      name: data.name,
      category: data.category,
      amount: Number(data.amount),
      date,
      month,
      year,
      autoGenerated: false,
    },
  });

  // Invalidate affected caches
  await deleteCache(cacheKeys.expenses(userId, month, year));
  await deleteCache(cacheKeys.summary(userId, month, year));

  return { success: true };
}

export async function updateExpense(id: string, data: ExpenseData) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  const userId = session.user.id;
  const date = new Date(data.date);
  const month = date.getMonth() + 1;
  const year = date.getFullYear();

  await db.expense.update({
    where: { id, userId },
    data: {
      name: data.name,
      category: data.category,
      amount: Number(data.amount),
      date,
      month,
      year,
    },
  });

  // Invalidate affected caches
  await deleteCache(cacheKeys.expenses(userId, month, year));
  await deleteCache(cacheKeys.summary(userId, month, year));

  return { success: true };
}

export async function deleteExpense(id: string) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  const userId = session.user.id;

  // Get expense first to know which month cache to invalidate
  const expense = await db.expense.findUnique({ where: { id } });

  await db.expense.delete({ where: { id, userId } });

  if (expense) {
    await deleteCache(cacheKeys.expenses(userId, expense.month, expense.year));
    await deleteCache(cacheKeys.summary(userId, expense.month, expense.year));
  }

  return { success: true };
}