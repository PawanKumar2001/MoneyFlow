"use server";

import { db } from "@/lib/db";
import { auth } from "@/lib/auth";
import { revalidatePath } from "next/cache";

type SubscriptionData = {
  name: string;
  amount: number;
  recurringDate: number;
  startMonth: number;
  startYear: number;
};

export async function getSubscriptions() {
  const session = await auth();
  if (!session?.user?.id) return [];

  return await db.subscription.findMany({
    where: { userId: session.user.id, isActive: true },
    orderBy: { createdAt: "desc" },
  });
}

export async function addSubscription(data: SubscriptionData) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  if (data.recurringDate < 1 || data.recurringDate > 28) {
    return { error: "Recurring date must be between 1 and 28." };
  }

  const subscription = await db.subscription.create({
    data: {
      userId: session.user.id,
      name: data.name,
      amount: Number(data.amount),
      recurringDate: Number(data.recurringDate),
      startMonth: Number(data.startMonth),
      startYear: Number(data.startYear),
      isActive: true,
    },
  });

  // Generate expense for current month if subscription started
  await generateSubscriptionExpense(subscription.id, session.user.id);

  revalidatePath("/dashboard/subscriptions");
  return { success: true };
}

export async function updateSubscription(id: string, data: SubscriptionData) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  if (data.recurringDate < 1 || data.recurringDate > 28) {
    return { error: "Recurring date must be between 1 and 28." };
  }

  await db.subscription.update({
    where: { id, userId: session.user.id },
    data: {
      name: data.name,
      amount: Number(data.amount),
      recurringDate: Number(data.recurringDate),
      startMonth: Number(data.startMonth),
      startYear: Number(data.startYear),
    },
  });

  revalidatePath("/dashboard/subscriptions");
  return { success: true };
}

export async function deleteSubscription(id: string) {
  const session = await auth();
  if (!session?.user?.id) return { error: "Unauthorized" };

  const now = new Date();
  const currentMonth = now.getMonth() + 1;
  const currentYear = now.getFullYear();

  // Deactivate subscription
  await db.subscription.update({
    where: { id, userId: session.user.id },
    data: { isActive: false },
  });

  // Delete current and future auto-generated expenses from this subscription
  const expensesToDelete = await db.expense.findMany({
    where: {
      userId: session.user.id,
      sourceSubscriptionId: id,
      autoGenerated: true,
    },
  });

  for (const expense of expensesToDelete) {
    const isFutureOrCurrent =
      expense.year > currentYear ||
      (expense.year === currentYear && expense.month >= currentMonth);

    if (isFutureOrCurrent) {
      await db.expense.delete({ where: { id: expense.id } });
    }
  }

  revalidatePath("/dashboard");
  revalidatePath("/dashboard/subscriptions");
  return { success: true };
}

async function generateSubscriptionExpense(
  subscriptionId: string,
  userId: string
) {
  const subscription = await db.subscription.findUnique({
    where: { id: subscriptionId },
  });

  if (!subscription) return;

  const now = new Date();
  const currentMonth = now.getMonth() + 1;
  const currentYear = now.getFullYear();

  // Check if subscription is active for current month
  const isActiveThisMonth =
    subscription.startYear < currentYear ||
    (subscription.startYear === currentYear &&
      subscription.startMonth <= currentMonth);

  if (!isActiveThisMonth) return;

  // Check if expense already generated for this month
  const existing = await db.expense.findFirst({
    where: {
      userId,
      sourceSubscriptionId: subscriptionId,
      month: currentMonth,
      year: currentYear,
    },
  });

  if (existing) return;

  // Generate the expense
  const expenseDate = new Date(
    currentYear,
    currentMonth - 1,
    subscription.recurringDate
  );

  await db.expense.create({
    data: {
      userId,
      name: subscription.name,
      category: "Utilities & Bills",
      amount: subscription.amount,
      date: expenseDate,
      month: currentMonth,
      year: currentYear,
      autoGenerated: true,
      sourceSubscriptionId: subscriptionId,
    },
  });
}