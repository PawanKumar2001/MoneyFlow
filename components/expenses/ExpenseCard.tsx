"use client";

import { motion } from "framer-motion";
import { Pencil, Trash2 } from "lucide-react";
import { getCurrencySymbol } from "@/lib/currency";

type Expense = {
  id: string;
  name: string;
  category: string;
  amount: number;
  date: Date;
  autoGenerated: boolean;
};

type Props = {
  expense: Expense;
  currency: string;
  onEdit: (expense: Expense) => void;
  onDelete: (id: string) => void;
  index: number;
};


const CATEGORY_COLORS: Record<string, string> = {
  "Grocery": "bg-emerald-500/20 text-emerald-400",
  "Food & Dining": "bg-orange-500/20 text-orange-400",
  "Transportation": "bg-blue-500/20 text-blue-400",
  "Utilities & Bills": "bg-yellow-500/20 text-yellow-400",
  "Healthcare": "bg-red-500/20 text-red-400",
  "Rent/Housing": "bg-purple-500/20 text-purple-400",
  "Entertainment": "bg-pink-500/20 text-pink-400",
  "Shopping": "bg-cyan-500/20 text-cyan-400",
  "Education": "bg-indigo-500/20 text-indigo-400",
  "Travel": "bg-teal-500/20 text-teal-400",
  "Others": "bg-slate-500/20 text-slate-400",
};

export default function ExpenseCard({
  expense,
  currency,
  onEdit,
  onDelete,
  index,
}: Props) {
  const symbol = getCurrencySymbol(currency);
  const isExpensive = expense.amount > 5000;
  const categoryColor = CATEGORY_COLORS[expense.category] ?? "bg-slate-500/20 text-slate-400";

  return (
    <motion.div
      initial={{ opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.3, delay: index * 0.05 }}
      className="group flex items-center justify-between p-4 rounded-xl border border-white/10 bg-white/5 hover:bg-white/10 hover:border-white/20 transition-all duration-200 hover:shadow-lg hover:-translate-y-0.5"
    >
      <div className="flex items-center gap-2 min-w-0">
        {/* Category Badge */}
        <span className={`shrink-0 hidden sm:inline px-2 py-1 rounded-lg text-xs font-medium ${categoryColor}`}>
          {expense.category}
        </span>

        {/* Name + Date */}
        <div className="min-w-0">
          <p className="text-sm font-medium text-white truncate">{expense.name}</p>
          <p className="text-xs text-slate-500">
            {new Date(expense.date).toLocaleDateString("en-US", {
              day: "numeric",
              month: "short",
              year: "numeric",
            })}
            {expense.autoGenerated && (
              <span className="ml-2 text-indigo-400">· Auto</span>
            )}
          </p>
        </div>
      </div>

      {/* Amount + Actions */}
      <div className="flex items-center gap-3 shrink-0">
        <span className={`text-sm font-bold ${isExpensive ? "text-red-400" : "text-emerald-400"}`}>
          {symbol}{expense.amount.toLocaleString()}
        </span>

        {/* Action Buttons */}
        <div className="flex items-center gap-1">
          {/* Edit — only for manual expenses */}
          {!expense.autoGenerated && (
            <button
              onClick={() => onEdit(expense)}
              className="p-1.5 rounded-lg hover:bg-indigo-500/20 text-slate-400 hover:text-indigo-400 transition-colors"
            >
              <Pencil className="h-3.5 w-3.5" />
            </button>
          )}

          {/* Delete — available for all expenses */}
          <button
            onClick={() => onDelete(expense.id)}
            className="p-1.5 rounded-lg hover:bg-red-500/20 text-slate-400 hover:text-red-400 transition-colors"
          >
            <Trash2 className="h-3.5 w-3.5" />
          </button>
        </div>
      </div>
    </motion.div>
  );
}