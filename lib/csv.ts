type Expense = {
  name: string;
  category: string;
  amount: number;
  date: Date;
  autoGenerated: boolean;
};

export function generateExpenseCSV(
  expenses: Expense[],
  currency: string,
  month: number,
  year: number
): string {
  const MONTHS = [
    "January", "February", "March", "April",
    "May", "June", "July", "August",
    "September", "October", "November", "December",
  ];

  const header = [
    "Name",
    "Category",
    `Amount (${currency})`,
    "Date",
    "Type",
  ].join(",");

  const rows = expenses.map((e) => {
    const date = new Date(e.date).toLocaleDateString("en-US", {
      day: "numeric",
      month: "short",
      year: "numeric",
    });
    const type = e.autoGenerated ? "Auto (Subscription)" : "Manual";
    // Wrap name and category in quotes to handle commas
    return [
      `"${e.name}"`,
      `"${e.category}"`,
      e.amount,
      date,
      type,
    ].join(",");
  });

  const totalRow = [
    `"TOTAL"`,
    `""`,
    expenses.reduce((sum, e) => sum + e.amount, 0),
    `""`,
    `""`,
  ].join(",");

  return [
    `MoneyFlow Export - ${MONTHS[month - 1]} ${year}`,,
    "",
    header,
    ...rows,
    "",
    totalRow,
  ].join("\n");
}

export function downloadCSV(content: string, filename: string) {
  const blob = new Blob(["\uFEFF" + content], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.setAttribute("download", filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}