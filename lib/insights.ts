type Expense = {
  category: string;
  amount: number;
  autoGenerated: boolean;
};

type CategoryData = {
  name: string;
  value: number;
};

type InsightData = {
  totalIncome: number;
  totalExpenses: number;
  totalSubscriptions: number;
  remaining: number;
  savingsPercent: string;
  byCategory: CategoryData[];
  expenses: Expense[];
  incomeType: string;
};

type Insight = {
  icon: string;
  title: string;
  description: string;
  color: string;
};

export function generateInsights(data: InsightData): Insight[] {
  const insights: Insight[] = [];
  const {
    totalIncome,
    totalExpenses,
    totalSubscriptions,
    savingsPercent,
    byCategory,
    expenses,
    incomeType,
  } = data;

  const isFreelancer = incomeType === "FREELANCER";

  // No income logged yet for freelancer
  if (isFreelancer && totalIncome === 0) {
    insights.push({
      icon: "📋",
      title: "No income logged yet",
      description:
        "Log your earnings for this month using the Log Income button to see insights.",
      color: "border-yellow-500/20 bg-yellow-500/10",
    });
    return insights;
  }

  // Savings insight
  const savings = parseFloat(savingsPercent);
  if (savings >= 30) {
    insights.push({
      icon: "🎉",
      title: "Great savings!",
      description: `You saved ${savingsPercent}% of your ${isFreelancer ? "earnings" : "income"} this month. Keep it up!`,
      color: "border-emerald-500/20 bg-emerald-500/10",
    });
  } else if (savings > 0) {
    insights.push({
      icon: "💡",
      title: "Room to save more",
      description: `You saved ${savingsPercent}% this month. Try to aim for 30% or more.`,
      color: "border-yellow-500/20 bg-yellow-500/10",
    });
  } else if (savings < 0) {
    insights.push({
      icon: "⚠️",
      title: "Overspending alert",
      description: `You spent more than your ${isFreelancer ? "earnings" : "income"} this month. Review your expenses.`,
      color: "border-red-500/20 bg-red-500/10",
    });
  }

  // Freelancer specific insight
  if (isFreelancer && totalIncome > 0) {
    insights.push({
      icon: "📈",
      title: "Variable income tracked",
      description: `You earned a total of this month across all your income sources.`,
      color: "border-emerald-500/20 bg-emerald-500/10",
    });
  }

  // Top category insight
  if (byCategory.length > 0) {
    const top = byCategory[0];
    const percent =
      totalExpenses > 0
        ? ((top.value / totalExpenses) * 100).toFixed(0)
        : "0";
    insights.push({
      icon: "📊",
      title: `${top.name} is your top expense`,
      description: `You spent the most on ${top.name} — ${percent}% of total expenses.`,
      color: "border-indigo-500/20 bg-indigo-500/10",
    });
  }

  // Subscription insight
  if (totalSubscriptions > 0 && totalIncome > 0) {
    const subPercent = ((totalSubscriptions / totalIncome) * 100).toFixed(0);
    insights.push({
      icon: "🔄",
      title: "Subscription spend",
      description: `Subscriptions consume ${subPercent}% of your monthly ${isFreelancer ? "earnings" : "income"}.`,
      color:
        parseInt(subPercent) > 20
          ? "border-red-500/20 bg-red-500/10"
          : "border-blue-500/20 bg-blue-500/10",
    });
  }

  // Auto-generated expenses
  const autoCount = expenses.filter((e) => e.autoGenerated).length;
  if (autoCount > 0) {
    insights.push({
      icon: "⚡",
      title: `${autoCount} auto-tracked expense${autoCount > 1 ? "s" : ""}`,
      description: `${autoCount} expense${autoCount > 1 ? "s were" : " was"} automatically generated from your subscriptions.`,
      color: "border-purple-500/20 bg-purple-500/10",
    });
  }

  // Budget usage
  if (totalIncome > 0) {
    const usagePercent = ((totalExpenses / totalIncome) * 100).toFixed(0);
    if (parseInt(usagePercent) > 90) {
      insights.push({
        icon: "🔴",
        title: "Budget almost exhausted",
        description: `You've used ${usagePercent}% of your monthly ${isFreelancer ? "earnings" : "income"}. Be careful with spending.`,
        color: "border-red-500/20 bg-red-500/10",
      });
    }
  }

  return insights.slice(0, 5);
}