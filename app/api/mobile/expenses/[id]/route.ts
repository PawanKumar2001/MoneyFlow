// Place at: app/api/mobile/expenses/[id]/route.ts

import { NextRequest, NextResponse } from "next/server";
import { db } from "@/lib/db";
import { verifyMobileToken } from "@/lib/mobile-auth";
import { redis } from "@/lib/redis";

function cacheKey(userId: string, month: number, year: number) {
  return `expenses:${userId}:${month}:${year}`;
}

// PATCH /api/mobile/expenses/[id]
export async function PATCH(
  req: NextRequest,
  { params }: { params: { id: string } }
) {
  try {
    const token = req.headers.get("authorization")?.replace("Bearer ", "");
    if (!token) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    const payload = await verifyMobileToken(token);
    if (!payload) return NextResponse.json({ error: "Invalid token" }, { status: 401 });

    const expense = await db.expense.findUnique({ where: { id: params.id } });
    if (!expense || expense.userId !== payload.userId) {
      return NextResponse.json({ error: "Not found" }, { status: 404 });
    }

    if (expense.autoGenerated) {
      return NextResponse.json(
        { error: "Auto-generated expenses cannot be edited" },
        { status: 403 }
      );
    }

    const { name, category, amount, date } = await req.json();
    const parsedDate = date ? new Date(date) : expense.date;
    const month = parsedDate.getMonth() + 1;
    const year = parsedDate.getFullYear();

    const updated = await db.expense.update({
      where: { id: params.id },
      data: {
        name: name ?? expense.name,
        category: category ?? expense.category,
        amount: amount ? parseFloat(amount) : expense.amount,
        date: parsedDate,
        month,
        year,
      },
    });

    // Invalidate both old and new month cache in case month changed
    await redis.del(cacheKey(payload.userId, expense.month, expense.year));
    await redis.del(cacheKey(payload.userId, month, year));

    return NextResponse.json({ expense: updated });
  } catch (error) {
    console.error("[MOBILE_EXPENSES_PATCH]", error);
    return NextResponse.json({ error: "Internal server error" }, { status: 500 });
  }
}

// DELETE /api/mobile/expenses/[id]
export async function DELETE(
  req: NextRequest,
  { params }: { params: { id: string } }
) {
  try {
    const token = req.headers.get("authorization")?.replace("Bearer ", "");
    if (!token) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    const payload = await verifyMobileToken(token);
    if (!payload) return NextResponse.json({ error: "Invalid token" }, { status: 401 });

    const expense = await db.expense.findUnique({ where: { id: params.id } });
    if (!expense || expense.userId !== payload.userId) {
      return NextResponse.json({ error: "Not found" }, { status: 404 });
    }

    await db.expense.delete({ where: { id: params.id } });

    // Invalidate cache
    await redis.del(cacheKey(payload.userId, expense.month, expense.year));

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error("[MOBILE_EXPENSES_DELETE]", error);
    return NextResponse.json({ error: "Internal server error" }, { status: 500 });
  }
}
