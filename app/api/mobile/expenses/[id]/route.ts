// app/api/mobile/expenses/[id]/route.ts

import { NextRequest, NextResponse } from "next/server";
import { db } from "@/lib/db";
import { verifyMobileToken } from "@/lib/mobile-auth";
import { redis } from "@/lib/redis";

function expenseCacheKey(userId: string, month: number, year: number) {
  return `expenses:${userId}:${month}:${year}`;
}

function summaryCacheKey(userId: string, month: number, year: number) {
  return `summary:${userId}:${month}:${year}`;
}

async function clearCaches(userId: string, month: number, year: number) {
  await Promise.all([
    redis.del(expenseCacheKey(userId, month, year)),
    redis.del(summaryCacheKey(userId, month, year)),
  ]);
}

function parseOptionalRequiredNumber(value: unknown, fallback: number) {
  if (value === undefined || value === null || value === "") {
    return fallback;
  }

  const parsed = Number(value);

  return Number.isFinite(parsed) ? parsed : fallback;
}

function parseOptionalDate(value: unknown, fallback: Date) {
  if (value === undefined || value === null || value === "") {
    return fallback;
  }

  const parsed = new Date(String(value));

  return Number.isNaN(parsed.getTime()) ? fallback : parsed;
}

// PATCH /api/mobile/expenses/[id]
export async function PATCH(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;

    const token = req.headers.get("authorization")?.replace("Bearer ", "");

    if (!token) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const payload = await verifyMobileToken(token);

    if (!payload) {
      return NextResponse.json({ error: "Invalid token" }, { status: 401 });
    }

    const expense = await db.expense.findUnique({
      where: { id },
    });

    if (!expense || expense.userId !== payload.userId) {
      return NextResponse.json({ error: "Not found" }, { status: 404 });
    }

    if (expense.autoGenerated) {
      return NextResponse.json(
        { error: "Auto-generated expenses cannot be edited" },
        { status: 403 }
      );
    }

    const { name, category, amount, date } = await req.json();

    const parsedDate = parseOptionalDate(date, expense.date);
    const parsedAmount = parseOptionalRequiredNumber(amount, expense.amount);

    const month = parsedDate.getMonth() + 1;
    const year = parsedDate.getFullYear();

    const updated = await db.expense.update({
      where: { id },
      data: {
        name: name ?? expense.name,
        category: category ?? expense.category,
        amount: parsedAmount,
        date: parsedDate,
        month,
        year,
      },
    });

    // Clear caches for both old and new month
    await Promise.all([
      clearCaches(payload.userId, expense.month, expense.year),
      clearCaches(payload.userId, month, year),
    ]);

    return NextResponse.json({ expense: updated });
  } catch (error) {
    console.error("[MOBILE_EXPENSES_PATCH]", error);

    return NextResponse.json(
      { error: "Internal server error" },
      { status: 500 }
    );
  }
}

// DELETE /api/mobile/expenses/[id]
export async function DELETE(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;

    const token = req.headers.get("authorization")?.replace("Bearer ", "");

    if (!token) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const payload = await verifyMobileToken(token);

    if (!payload) {
      return NextResponse.json({ error: "Invalid token" }, { status: 401 });
    }

    const expense = await db.expense.findUnique({
      where: { id },
    });

    if (!expense || expense.userId !== payload.userId) {
      return NextResponse.json({ error: "Not found" }, { status: 404 });
    }

    await db.expense.delete({
      where: { id },
    });

    // Clear both expenses and summary cache
    await clearCaches(payload.userId, expense.month, expense.year);

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error("[MOBILE_EXPENSES_DELETE]", error);

    return NextResponse.json(
      { error: "Internal server error" },
      { status: 500 }
    );
  }
}