"use client";

import { useEffect, useRef, useState } from "react";
import { useMonthStore } from "@/store/monthStore";
import { getMonthlySummary, getMonthlyTrend } from "@/actions/summary";
import { generateInsights } from "@/lib/insights";
import { getCurrencySymbol, formatAmount } from "@/lib/currency";
import { motion } from "framer-motion";
import ChartSkeleton from "@/components/shared/ChartSkelton";
import { generateExpenseCSV, downloadCSV } from "@/lib/csv";
import { Download } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  BarChart,
  Bar,
  XAxis,
  YAxis,
  Tooltip,
  ResponsiveContainer,
  PieChart,
  Pie,
  Cell,
  LineChart,
  Line,
} from "recharts";

type SummaryData = {
  expenses: {
    id: string;
    name: string;
    category: string;
    amount: number;
    date: Date;
    autoGenerated: boolean;
  }[];
  totalIncome: number;
  totalExpenses: number;
  totalSubscriptions: number;
  remaining: number;
  savingsPercent: string;
  byCategory: { name: string; value: number }[];
  incomeType: string;
  currency: string;
};

type TrendData = {
  name: string;
  expenses: number;
  income: number;
}[];

const PIE_COLORS = [
  "#6366f1",
  "#10b981",
  "#f59e0b",
  "#ef4444",
  "#8b5cf6",
  "#06b6d4",
  "#f97316",
  "#84cc16",
];

const TABS = ["Chart View", "Table View"];
const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

export default function SummaryPage() {
  const { month, year } = useMonthStore();
  const [data, setData] = useState<SummaryData | null>(null);
  const [trend, setTrend] = useState<TrendData>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState(0);
  const [retryKey, setRetryKey] = useState(0);

  const cacheRef = useRef<{
    key: string;
    data: SummaryData;
    trend: TrendData;
  } | null>(null);

  useEffect(() => {
    let isMounted = true;
    const cacheKey = `${month}-${year}`;

    if (cacheRef.current?.key === cacheKey && retryKey === 0) {
      setData(cacheRef.current.data);
      setTrend(cacheRef.current.trend);
      setLoading(false);
      setError(null);
      return;
    }

    const fetchData = async () => {
      try {
        setLoading(true);
        setError(null);

        const [summaryResult, trendResult] = await Promise.allSettled([
          getMonthlySummary(month, year),
          getMonthlyTrend(month, year),
        ]);

        if (!isMounted) return;

        if (summaryResult.status === "rejected" || !summaryResult.value) {
          throw new Error("Monthly summary request failed.");
        }

        const summaryData = summaryResult.value as SummaryData;
        const safeSummaryData: SummaryData = {
          ...summaryData,
          expenses: summaryData.expenses ?? [],
          byCategory: summaryData.byCategory ?? [],
        };

        const trendData =
          trendResult.status === "fulfilled" && Array.isArray(trendResult.value)
            ? (trendResult.value as TrendData)
            : [];

        cacheRef.current = {
          key: cacheKey,
          data: safeSummaryData,
          trend: trendData,
        };

        setData(safeSummaryData);
        setTrend(trendData);
      } catch (err) {
        console.error("Failed to load summary page:", err);

        if (!isMounted) return;

        setError("Could not load summary. Please try again.");
        setData(null);
        setTrend([]);
      } finally {
        if (isMounted) {
          setLoading(false);
        }
      }
    };

    fetchData();

    return () => {
      isMounted = false;
    };
  }, [month, year, retryKey]);

  const symbol = data ? getCurrencySymbol(data.currency) : "₹";
  const isFreelancer = data?.incomeType === "FREELANCER";
  const hasExpenses = (data?.expenses.length ?? 0) > 0;
  const hasIncome = (data?.totalIncome ?? 0) > 0;

  const insights = data
    ? generateInsights(data).map((insight) => ({
        ...insight,
        description: insight.description.replace(
          /a total\s+of this month/i,
          `a total of ${symbol}${formatAmount(data.totalIncome)} this month`
        ),
      }))
    : [];

  const barData = [
    {
      name: isFreelancer ? "Earnings" : "Income",
      value: data?.totalIncome ?? 0,
      fill: "#10b981",
    },
    { name: "Expenses", value: data?.totalExpenses ?? 0, fill: "#ef4444" },
    {
      name: "Remaining",
      value: Math.max(data?.remaining ?? 0, 0),
      fill: "#6366f1",
    },
  ];

  const handleExport = () => {
    if (!data || data.expenses.length === 0) return;

    const csv = generateExpenseCSV(data.expenses, data.currency, month, year);
    downloadCSV(csv, `MoneyFlow_${MONTHS[month - 1]}_${year}.csv`);
  };

  if (loading) {
    return (
      <div className="px-6 md:px-12 lg:px-20 pt-6 space-y-6 pb-8">
        <div className="space-y-2">
          <div className="h-6 w-48 rounded-lg bg-white/5 animate-pulse" />
          <div className="h-4 w-64 rounded-lg bg-white/5 animate-pulse" />
        </div>

        <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
          {[...Array(4)].map((_, i) => (
            <div
              key={i}
              className="rounded-xl border border-white/10 bg-white/5 p-4 space-y-2 animate-pulse"
            >
              <div className="h-3 w-16 rounded bg-white/10" />
              <div className="h-6 w-24 rounded bg-white/10" />
            </div>
          ))}
        </div>

        <div className="h-9 w-48 rounded-xl bg-white/5 animate-pulse" />

        <div className="space-y-6">
          <div className="rounded-xl border border-white/10 bg-white/5 p-4 space-y-4">
            <div className="h-4 w-36 rounded bg-white/10 animate-pulse" />
            <ChartSkeleton height={220} />
          </div>
          <div className="rounded-xl border border-white/10 bg-white/5 p-4 space-y-4">
            <div className="h-4 w-36 rounded bg-white/10 animate-pulse" />
            <ChartSkeleton height={260} />
          </div>
        </div>
      </div>
    );
  }

  if (error) {
    return (
      <div className="px-6 md:px-12 lg:px-20 pt-6">
        <div className="flex flex-col items-center justify-center py-24 text-center">
          <div className="text-5xl mb-4">⚠️</div>
          <h3 className="text-xl font-semibold text-white mb-2">
            Could not load summary
          </h3>
          <p className="text-sm text-slate-400 max-w-sm mb-5">
            Something went wrong while loading your monthly summary.
          </p>
          <button
            onClick={() => setRetryKey((key) => key + 1)}
            className="rounded-lg bg-white text-black px-4 py-2 text-sm font-medium hover:bg-slate-200 transition"
          >
            Try again
          </button>
        </div>
      </div>
    );
  }

  if (!hasExpenses && !hasIncome) {
    return (
      <div className="px-6 md:px-12 lg:px-20 pt-6">
        <div className="flex flex-col items-center justify-center py-24 text-center">
          <motion.div
            animate={{ y: [0, -8, 0] }}
            transition={{ repeat: Infinity, duration: 3, ease: "easeInOut" }}
            className="text-6xl mb-4"
          >
            📊
          </motion.div>
          <h3 className="text-xl font-semibold text-white mb-2">
            No data for this month
          </h3>
          <p className="text-sm text-slate-400 max-w-sm mb-2">
            Add some expenses or{" "}
            {isFreelancer ? "log your income" : "check your income setup"} to
            see your monthly summary here.
          </p>
          <p className="text-xs text-slate-500">
            Navigate to the Expenses tab to get started.
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="px-6 md:px-12 lg:px-20 pt-6 space-y-6 pb-8">
      <div className="flex items-center justify-between gap-4">
        <div>
          <h2 className="text-lg font-bold text-white">Monthly Summary</h2>
          <p className="text-xs text-slate-400 flex items-center gap-2">
            Overview of your finances for this month
          </p>
        </div>

        {hasExpenses && (
          <Button
            onClick={handleExport}
            variant="outline"
            className="border-white/10 text-slate-300 hover:bg-white/5 gap-2 text-sm shrink-0"
          >
            <Download className="h-4 w-4" />
            <span className="hidden sm:inline">Export CSV</span>
          </Button>
        )}
      </div>

      <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
        {[
          {
            label: isFreelancer ? "Earnings" : "Income",
            value: `${symbol}${formatAmount(data!.totalIncome)}`,
            color: "text-emerald-400",
          },
          {
            label: "Expenses",
            value: `${symbol}${formatAmount(data!.totalExpenses)}`,
            color: "text-red-400",
          },
          {
            label: "Remaining",
            value: `${symbol}${formatAmount(Math.max(data!.remaining, 0))}`,
            color: "text-indigo-400",
          },
          {
            label: "Savings",
            value: `${data!.savingsPercent}%`,
            color: "text-yellow-400",
          },
        ].map((stat, i) => (
          <motion.div
            key={stat.label}
            initial={{ opacity: 0, y: 16 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: i * 0.1 }}
            className="rounded-xl border border-white/10 bg-white/5 p-4"
          >
            <p className="text-xs text-slate-500 mb-1">{stat.label}</p>
            <p className={`text-lg font-bold ${stat.color}`}>{stat.value}</p>
          </motion.div>
        ))}
      </div>

      <div className="flex gap-1 p-1 rounded-xl bg-white/5 border border-white/10 w-fit">
        {TABS.map((tab, i) => (
          <button
            key={tab}
            onClick={() => setActiveTab(i)}
            className={`px-4 py-1.5 rounded-lg text-sm font-medium transition-all ${
              activeTab === i
                ? "bg-white text-black shadow"
                : "text-slate-400 hover:text-white"
            }`}
          >
            {tab}
          </button>
        ))}
      </div>

      {activeTab === 0 && (
        <div className="space-y-6">
          <div className="rounded-xl border border-white/10 bg-white/5 p-4 overflow-hidden">
            <h3 className="text-sm font-semibold text-white mb-4">
              {isFreelancer ? "Earnings vs Expenses" : "Income vs Expenses"}
            </h3>

            <ResponsiveContainer width="100%" height={220}>
              <BarChart data={barData} barSize={48}>
                <XAxis
                  dataKey="name"
                  tick={{ fill: "#94a3b8", fontSize: 12 }}
                  axisLine={false}
                  tickLine={false}
                />
                <YAxis
                  tick={{ fill: "#94a3b8", fontSize: 11 }}
                  axisLine={false}
                  tickLine={false}
                  tickFormatter={(v) => `${symbol}${(v / 1000).toFixed(0)}k`}
                />
                <Tooltip
                  contentStyle={{
                    backgroundColor: "rgba(0,0,0,0.9)",
                    border: "1px solid rgba(255,255,255,0.2)",
                    borderRadius: "12px",
                    color: "#fff",
                  }}
                  itemStyle={{ color: "#fff" }}
                  labelStyle={{ color: "#fff" }}
                  cursor={{
                    fill: "transparent",
                    stroke: "rgba(255,255,255,0.2)",
                    strokeWidth: 1,
                  }}
                  formatter={(value) => [
                    `${symbol}${Number(value).toLocaleString()}`,
                    "",
                  ]}
                />
                <Bar dataKey="value" radius={[6, 6, 0, 0]} cursor="default">
                  {barData.map((entry, i) => (
                    <Cell key={i} fill={entry.fill} />
                  ))}
                </Bar>
              </BarChart>
            </ResponsiveContainer>
          </div>

          {trend.length > 0 && (
            <div className="rounded-xl border border-white/10 bg-white/5 p-4 overflow-hidden">
              <h3 className="text-sm font-semibold text-white mb-4">
                {isFreelancer
                  ? "6-Month Income & Expense Trend"
                  : "6-Month Spending Trend"}
              </h3>
              <ResponsiveContainer width="100%" height={220}>
                <LineChart data={trend}>
                  <XAxis
                    dataKey="name"
                    tick={{ fill: "#94a3b8", fontSize: 12 }}
                    axisLine={false}
                    tickLine={false}
                  />
                  <YAxis
                    tick={{ fill: "#94a3b8", fontSize: 11 }}
                    axisLine={false}
                    tickLine={false}
                    tickFormatter={(v) =>
                      `${symbol}${(v / 1000).toFixed(0)}k`
                    }
                  />
                  <Tooltip
                    contentStyle={{
                      backgroundColor: "rgba(0,0,0,0.9)",
                      border: "1px solid rgba(255,255,255,0.2)",
                      borderRadius: "12px",
                      color: "#fff",
                    }}
                    itemStyle={{ color: "#fff" }}
                    labelStyle={{ color: "#fff" }}
                    cursor={{
                      fill: "transparent",
                      stroke: "rgba(255,255,255,0.2)",
                      strokeWidth: 1,
                    }}
                    formatter={(value) => [
                      `${symbol}${Number(value).toLocaleString()}`,
                      "",
                    ]}
                  />
                  {isFreelancer && (
                    <Line
                      type="monotone"
                      dataKey="income"
                      stroke="#10b981"
                      strokeWidth={2}
                      dot={{ fill: "#10b981", r: 4 }}
                      name="Earnings"
                    />
                  )}
                  <Line
                    type="monotone"
                    dataKey="expenses"
                    stroke="#ef4444"
                    strokeWidth={2}
                    dot={{ fill: "#ef4444", r: 4 }}
                    name="Expenses"
                  />
                </LineChart>
              </ResponsiveContainer>
            </div>
          )}

          {data!.byCategory.length > 0 ? (
            <div className="rounded-xl border border-white/10 bg-white/5 p-4 overflow-hidden">
              <h3 className="text-sm font-semibold text-white mb-4">
                Spending by Category
              </h3>

              <div className="h-[220px] sm:h-[260px]">
                <ResponsiveContainer width="100%" height="100%">
                  <PieChart>
                    <Pie
                      data={data!.byCategory}
                      cx="50%"
                      cy="50%"
                      innerRadius="45%"
                      outerRadius="75%"
                      paddingAngle={3}
                      dataKey="value"
                      isAnimationActive={false}
                    >
                      {data!.byCategory.map((_, i) => (
                        <Cell
                          key={i}
                          fill={PIE_COLORS[i % PIE_COLORS.length]}
                          stroke="transparent"
                          style={{ outline: "none" }}
                        />
                      ))}
                    </Pie>
                    <Tooltip
                      cursor={false}
                      contentStyle={{
                        backgroundColor: "rgba(0,0,0,0.9)",
                        border: "1px solid rgba(255,255,255,0.2)",
                        borderRadius: "12px",
                        color: "#fff",
                      }}
                      itemStyle={{ color: "#fff" }}
                      labelStyle={{ color: "#fff" }}
                      formatter={(value) => [
                        `${symbol}${Number(value).toLocaleString()}`,
                        "",
                      ]}
                    />
                  </PieChart>
                </ResponsiveContainer>
              </div>

              <div className="mt-3 flex flex-wrap items-center justify-center gap-x-4 gap-y-2 px-2">
                {data!.byCategory.map((item, i) => (
                  <div key={item.name} className="flex items-center gap-1.5">
                    <span
                      className="h-3 w-3 shrink-0 rounded-sm"
                      style={{
                        backgroundColor: PIE_COLORS[i % PIE_COLORS.length],
                      }}
                    />
                    <span className="text-xs text-slate-400 leading-none">
                      {item.name}
                    </span>
                  </div>
                ))}
              </div>
            </div>
          ) : (
            <div className="rounded-xl border border-white/10 bg-white/5 p-4">
              <h3 className="text-sm font-semibold text-white mb-4">
                Spending by Category
              </h3>
              <div className="flex flex-col items-center justify-center h-40 gap-2">
                <span className="text-3xl">🥧</span>
                <p className="text-slate-500 text-sm">
                  No expenses to categorize yet
                </p>
              </div>
            </div>
          )}

          {insights.length > 0 && (
            <div className="space-y-3">
              <h3 className="text-sm font-semibold text-white">
                💡 Financial Insights
              </h3>
              {insights.map((insight, i) => (
                <motion.div
                  key={i}
                  initial={{ opacity: 0, x: -16 }}
                  animate={{ opacity: 1, x: 0 }}
                  transition={{ delay: i * 0.1 }}
                  className={`flex items-start gap-3 p-4 rounded-xl border ${insight.color}`}
                >
                  <span className="text-xl shrink-0">{insight.icon}</span>
                  <div>
                    <p className="text-sm font-medium text-white">
                      {insight.title}
                    </p>
                    <p className="text-xs text-slate-400 mt-0.5">
                      {insight.description}
                    </p>
                  </div>
                </motion.div>
              ))}
            </div>
          )}
        </div>
      )}

      {activeTab === 1 && (
        <div className="rounded-xl border border-white/10 bg-white/5 overflow-hidden">
          {!hasExpenses ? (
            <div className="flex flex-col items-center justify-center py-16 gap-3">
              <span className="text-4xl">🧾</span>
              <p className="text-slate-500 text-sm">
                No expenses recorded this month
              </p>
            </div>
          ) : (
            <>
              <div className="flex items-center justify-between px-4 py-3 border-b border-white/10">
                <p className="text-xs text-slate-400">
                  {data!.expenses.length} expense
                  {data!.expenses.length !== 1 ? "s" : ""}
                </p>
                <button
                  onClick={handleExport}
                  className="flex items-center gap-1.5 text-xs text-slate-400 hover:text-white transition-colors"
                >
                  <Download className="h-3.5 w-3.5" />
                  Export CSV
                </button>
              </div>

              <div className="overflow-x-auto">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="border-b border-white/10 text-left">
                      <th className="px-4 py-3 text-xs font-medium text-slate-400">
                        Name
                      </th>
                      <th className="px-4 py-3 text-xs font-medium text-slate-400">
                        Category
                      </th>
                      <th className="px-4 py-3 text-xs font-medium text-slate-400">
                        Amount
                      </th>
                      <th className="px-4 py-3 text-xs font-medium text-slate-400">
                        Date
                      </th>
                      <th className="px-4 py-3 text-xs font-medium text-slate-400">
                        Type
                      </th>
                    </tr>
                  </thead>
                  <tbody>
                    {data!.expenses.map((expense) => (
                      <tr
                        key={expense.id}
                        className="border-b border-white/5 hover:bg-white/5 transition-colors"
                      >
                        <td className="px-4 py-3 text-white font-medium">
                          {expense.name}
                        </td>
                        <td className="px-4 py-3 text-slate-400">
                          {expense.category}
                        </td>
                        <td className="px-4 py-3 font-semibold text-emerald-400">
                          {symbol}
                          {formatAmount(expense.amount)}
                        </td>
                        <td className="px-4 py-3 text-slate-400">
                          {new Date(expense.date).toLocaleDateString("en-US", {
                            day: "numeric",
                            month: "short",
                          })}
                        </td>
                        <td className="px-4 py-3">
                          <span
                            className={`px-2 py-0.5 rounded-full text-xs font-medium ${
                              expense.autoGenerated
                                ? "bg-indigo-500/20 text-indigo-400"
                                : "bg-slate-500/20 text-slate-400"
                            }`}
                          >
                            {expense.autoGenerated ? "Auto" : "Manual"}
                          </span>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                  <tfoot>
                    <tr className="border-t border-white/10 bg-white/5">
                      <td
                        colSpan={2}
                        className="px-4 py-3 text-slate-400 font-medium text-xs"
                      >
                        Total Expenses
                      </td>
                      <td className="px-4 py-3 font-bold text-red-400">
                        {symbol}
                        {formatAmount(data!.totalExpenses)}
                      </td>
                      <td colSpan={2} className="px-4 py-3 text-xs text-slate-500">
                        Remaining: {symbol}
                        {formatAmount(Math.max(data!.remaining, 0))}
                      </td>
                    </tr>
                  </tfoot>
                </table>
              </div>
            </>
          )}
        </div>
      )}
    </div>
  );
}
